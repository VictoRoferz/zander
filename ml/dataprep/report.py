"""
Dataset card v2: a committed, human-readable snapshot of what a model is
trained and evaluated on. Regenerated by `python cli.py report --schema def3`;
lives in ml/reports/dataset_card.md.

It deliberately puts the known weaknesses of the data next to the counts
(class <-> board confound, handheld negatives, lumpy groups), so nobody reads
a later metric without them.
"""
from __future__ import annotations

import json
import logging
import math
import statistics
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

from config.settings import settings
from dataprep.attributes import load_attributes
from dataprep.ingest import load_manifest, usable
from dataprep.remap import BOX_CLASSES, SHORT
from dataprep.split import bucket_of, load_split
from dataprep.tiler import dataset_id

logger = logging.getLogger("ml.report")

SIZE_BUCKETS = [(0, 16), (16, 32), (32, 64), (64, 128), (128, 10_000)]
BUCKET_ORDER = ["fold0", "fold1", "fold2", "train_always", "test"]


def _side(b) -> float:
    return math.sqrt(max((b[2] - b[0]) * (b[3] - b[1]), 0.0))


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def build_card(schema: str = "def3") -> str:
    manifest, split = load_manifest(), load_split()
    entries = manifest["entries"]
    use = [e for e in entries if usable(e)]
    bucket = {e["capture_id"]: bucket_of(e, split) for e in entries}

    lines = [
        "# Dataset card — solder-joint defect detection (zander)",
        "",
        f"_Generated {date.today().isoformat()} · snapshot `{manifest['snapshot_id']}` · "
        f"split `{split['split_id']}` (frozen at {split['frozen_at'][:10]}, K={split['k_folds']}) · "
        f"views `{dataset_id(schema)}`_",
        "",
        "Required output per photo: **N.iO + detected defect class(es)**, or **i.O**. "
        "Box classes: Nicht ausreichend Lot (NAL), Brücke, Fahne.",
        "",
        "## Photos",
        "",
    ]
    states = Counter(e["label_state"] for e in entries)
    quarantined = [e for e in entries if e["quarantine_reason"]]
    verdicts = Counter(e["verdict"] for e in use)
    lines += _table(
        ["state", "photos"],
        [[s, n] for s, n in sorted(states.items())]
        + [["quarantined (no usable PCB / fallback; any state)", len(quarantined)],
           ["**usable for train/eval**", f"**{len(use)}** (iO {verdicts['iO']}, NiO {verdicts['NiO']})"]],
    )

    # ---- confound ----
    lines += ["", "## Class ↔ board confound (usable photos)", ""]
    rows = []
    for c in BOX_CLASSES:
        per_board = Counter(e["board"] for e in use for n, _ in e["boxes"] if n == c)
        photos = Counter(e["board"] for e in use if c in e["classes_present"])
        rows.append([SHORT[c]] + [f"{per_board.get(b, 0)} / {photos.get(b, 0)}" for b in ("A", "A2", "B")])
    io = Counter((e["board"], e["pose"]) for e in use if e["verdict"] == "iO")
    rows.append(["iO photos"] + [
        f"{io.get((b, 'seated'), 0)} seated · {io.get((b, 'handheld'), 0)} handheld" for b in ("A", "A2", "B")
    ])
    lines += _table(["class", "board A (boxes / photos)", "A2", "B"], rows)
    lines += [
        "",
        "- **Brücke/Fahne live almost only on board B — one panel, one 16-min session.** "
        "Board B is `train_always` (never validated): its Brücke/Fahne numbers can only be "
        "reported as within-panel memorisation.",
        "- **Honest cross-product check** = the probe: the board-A/A2 Brücke/Fahne boxes are "
        "held out of every training view (tiles touching them are dropped). "
        f"{len(split['probe_boxes'])} boxes: "
        + ", ".join(f"{SHORT[c]} {n}" for c, n in sorted(Counter(p['class'] for p in split['probe_boxes']).items()))
        + " — results are hit counts, not rates.",
        "- **Production-pose negatives are scarce**: the false-call rate is measured on *seated* "
        "iO photos only; handheld iO photos are training negatives (capped) and a separate row.",
    ]

    # ---- split composition ----
    lines += ["", "## Split composition (usable photos)", ""]
    per = defaultdict(list)
    for e in use:
        per[bucket[e["capture_id"]]].append(e)
    rows = []
    for b in [b for b in BUCKET_ORDER if b in per] + sorted(set(per) - set(BUCKET_ORDER)):
        es = per[b]
        boxes = Counter(n for e in es for n, _ in e["boxes"])
        rows.append([
            b, len(es),
            sum(1 for e in es if e["verdict"] == "NiO"),
            sum(1 for e in es if e["verdict"] == "iO" and e["pose"] == "seated"),
            sum(1 for e in es if e["verdict"] == "iO" and e["pose"] == "handheld"),
            *[boxes.get(c, 0) for c in BOX_CLASSES],
            len({split["assignment"][e["capture_id"]]["group"] for e in es}),
        ])
    lines += _table(
        ["bucket", "photos", "NiO", "iO seated", "iO handheld", "NAL boxes", "Brücke boxes",
         "Fahne boxes", "groups"], rows,
    )
    groups = json.loads((settings.datasets_dir / split["groups_file"]).read_text(encoding="utf-8"))
    nal_groups = sorted(
        (g["n_nal_photos"] for g in groups["groups"].values() if g["n_nal_photos"]), reverse=True
    )
    lines += [
        "",
        f"Groups (`{split['groups_file']}`, edges {groups['params'].get('edges')}): "
        f"{len(nal_groups)} contain NAL; largest {nal_groups[:5]} NAL photos — the effective "
        "sample size is the number of groups, not photos.",
    ]

    # ---- box sizes ----
    lines += ["", "## Box sizes (sqrt-area px at native 2616×1960, usable photos)", ""]
    rows = []
    for c in BOX_CLASSES:
        sides = sorted(_side(b) for e in use for n, b in e["boxes"] if n == c)
        if not sides:
            continue
        rows.append([SHORT[c], len(sides), f"{statistics.median(sides):.0f}",
                     *[sum(1 for s in sides if lo <= s < hi) for lo, hi in SIZE_BUCKETS]])
    lines += _table(["class", "boxes", "median"] + [
        f"{lo}–{hi}" if hi < 10_000 else f">{lo}" for lo, hi in SIZE_BUCKETS], rows)

    # ---- colour stats vs augmentation ----
    attrs = load_attributes()
    by_sess = defaultdict(list)
    for e in use:
        a = attrs[e["capture_id"]]
        if a["board_L"]:
            by_sess[(a["session"], e["board"])].append(
                (float(a["luma_mean"]), float(a["board_L"]), float(a["board_a"]), float(a["board_b"]))
            )
    rows = []
    for (s, b), vals in sorted(by_sess.items()):
        med = [statistics.median(v[i] for v in vals) for i in range(4)]
        hue = math.degrees(math.atan2(med[3], med[2]))
        rows.append([s, b, len(vals), f"{med[0]:.0f}", f"{med[1]:.0f}", f"{med[2]:.1f}",
                     f"{med[3]:.1f}", f"{hue:.0f}°"])
    from train.ultralytics_run import DEFAULT_AUGMENT

    lines += ["", "## Colour / exposure per session vs. augmentation ranges", ""]
    lines += _table(["session", "board", "photos", "luma", "board L*", "a*", "b*", "hue(a*b*)"], rows)
    lumas = [float(r[3]) for r in rows]
    lines += [
        "",
        f"Session luma spans {min(lumas):.0f}–{max(lumas):.0f} "
        f"(±{(max(lumas) - min(lumas)) / 2 / statistics.median(lumas):.0%} around the median) → "
        f"online `hsv_v={DEFAULT_AUGMENT['hsv_v']}`, `hsv_s={DEFAULT_AUGMENT['hsv_s']}`, "
        f"small `hsv_h={DEFAULT_AUGMENT['hsv_h']}` (solder colour is signal). The large board-A ↔ "
        "board-B colour shift is NOT covered by HSV jitter — the offline cross-board colour "
        "transfer handles it.",
    ]

    # ---- views ----
    prov_path = settings.tiles_dir / dataset_id(schema) / "provenance.json"
    if prov_path.exists():
        p = json.loads(prov_path.read_text(encoding="utf-8"))
        lines += ["", f"## Training views `{p['dataset_id']}`", "",
                  f"- tiler `{p['tiler_version']}` {p['tile_size']} px / stride {p['stride']}, "
                  f"`{p['encoding']}`; {p['n_base_tiles']} base tiles from {p['n_photos_tiled']} photos",
                  f"- offline augmentation: `{p['augmentation']}`",
                  f"- dataset_fingerprint `{p['dataset_fingerprint'][:16]}…`", ""]
        rows = []
        for view, v in p["views"].items():
            parity = max(abs(a - b) for a, b in zip(v["orientation_pos"], v["orientation_neg"]))
            rows.append([
                view, v["n_entries"], v["n_unique_files"], f"{v['positive_share']:.2f}",
                " · ".join(f"{SHORT.get(c, c)} {n}" for c, n in sorted(v["instances"].items())),
                v.get("dropped_partial", "–"), v.get("dropped_probe", "–"),
                v.get("dropped_handheld_cap", "–"), f"{parity:.3f}",
                f"{v['ct_share_pos']:.2f}/{v['ct_share_neg']:.2f}",
            ])
        lines += _table(["view", "entries", "files", "pos share", "instances", "drop partial",
                         "drop probe", "drop handheld", "D4 parity Δ", "CT pos/neg"], rows)
        lines += ["", "D4 parity Δ = max difference of the orientation histograms of positive vs "
                  "negative entries — ≈0 on the *training* views means orientation carries no "
                  "label information (validation views are never trained on; their Δ is "
                  "small-sample noise)."]

    review = [e for e in entries if e["review_note"]]
    if review:
        lines += ["", "## Review list", ""]
        for e in review:
            lines.append(f"- `{e['capture_id']}` ({e['label_state']}): {e['review_note']}")
    return "\n".join(lines) + "\n"


def run(schema: str = "def3") -> Path:
    settings.reports_dir.mkdir(parents=True, exist_ok=True)
    out = settings.reports_dir / "dataset_card.md"
    out.write_text(build_card(schema), encoding="utf-8")
    logger.info(f"dataset card written: {out}")
    return out
